CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone VARCHAR(15),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('Landlord', 'Tenant')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE properties (
    property_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    landlord_id INT NOT NULL,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    rent_amt DECIMAL(10,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available', 'Occupied')),
    description TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_property_landlord
        FOREIGN KEY (landlord_id)
        REFERENCES users(user_id),

    CONSTRAINT chk_rent_amt
        CHECK (rent_amt >= 0)
);

CREATE TABLE tenants (
    tenant_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL,
    property_id INT NOT NULL,
    lease_start_date DATE NOT NULL,
    lease_end_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Ended')),

    CONSTRAINT fk_tenant_user
        FOREIGN KEY (user_id)
        REFERENCES users(user_id),

    CONSTRAINT fk_tenant_property
        FOREIGN KEY (property_id)
        REFERENCES properties(property_id),

    CONSTRAINT chk_lease_dates
        CHECK (
            lease_end_date IS NULL
            OR lease_end_date >= lease_start_date
        )
);

CREATE TABLE payments (
    payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id INT NOT NULL,
    property_id INT NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    due_date DATE NOT NULL,
    payment_date DATE,
    payment_month DATE NOT NULL,
    payment_method VARCHAR(50),
    status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Paid', 'Overdue')),

    CONSTRAINT fk_payment_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants(tenant_id),

    CONSTRAINT fk_payment_property
        FOREIGN KEY (property_id)
        REFERENCES properties(property_id),

    CONSTRAINT chk_payment_amount
        CHECK (amount >= 0),

    CONSTRAINT uq_tenant_rent_month
        UNIQUE (tenant_id, payment_month)
);

CREATE TABLE maintenance_requests (
    request_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id INT NOT NULL,
    property_id INT NOT NULL,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Submitted'
        CHECK (status IN ('Submitted', 'In Progress', 'Resolved')),
    priority VARCHAR(10) NOT NULL DEFAULT 'Medium'
        CHECK (priority IN ('Low', 'Medium', 'High')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP NULL DEFAULT NULL,

    CONSTRAINT fk_request_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants(tenant_id),

    CONSTRAINT fk_request_property
        FOREIGN KEY (property_id)
        REFERENCES properties(property_id)
);

CREATE TABLE lease_documents (
    document_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id INT NOT NULL,
    property_id INT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_path TEXT NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_lease_tenant
        FOREIGN KEY (tenant_id) REFERENCES tenants(tenant_id),

    CONSTRAINT fk_lease_property
        FOREIGN KEY (property_id) REFERENCES properties(property_id)
);

SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;

SELECT
    table_name,
    column_name,
    data_type,
    is_nullable
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name IN (
      'users',
      'properties',
      'tenants',
      'payments',
      'maintenance_requests',
	  'lease_documents'
  )
ORDER BY table_name, ordinal_position;
